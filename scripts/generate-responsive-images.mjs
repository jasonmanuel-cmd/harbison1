/**
 * Generates the responsive width variants for every property photo.
 *
 * Lighthouse flagged every listing image as over-served: a single 1600px file
 * was being sent to a 390px phone. These variants let the browser pick one
 * that actually matches the slot, which is where most of the mobile byte
 * savings come from.
 *
 * Writes public/images/property/resp/<slug>-<n>-<width>.webp and extends
 * lib/property-images.generated.ts with the srcset data.
 *
 * Run automatically by pnpm prebuild.
 */
import { readdirSync, writeFileSync, existsSync, mkdirSync } from 'node:fs'
import { join } from 'node:path'
import { execFileSync } from 'node:child_process'

const ROOT = process.cwd()
const SRC = join(ROOT, 'public', 'images', 'property')
const OUT_DIR = join(SRC, 'resp')
const MANIFEST = join(ROOT, 'lib', 'property-images.generated.ts')

const WIDTHS = [400, 640, 960, 1280, 1600]
const QUALITY = 76

if (!existsSync(SRC)) {
  console.error(`[responsive] missing ${SRC}`)
  process.exit(1)
}
mkdirSync(OUT_DIR, { recursive: true })

const sources = readdirSync(SRC).filter((f) => f.endsWith('.webp'))

function encode(input, output, width) {
  execFileSync('ffmpeg', [
    '-hide_banner', '-loglevel', 'error', '-i', input,
    '-vf', `scale=${width}:-2`,
    '-quality', String(QUALITY),
    '-compression_level', '6',
    '-y', output,
  ], { stdio: 'ignore' })
}

let made = 0
const variants = new Map()

for (const file of sources) {
  const base = file.replace(/\.webp$/, '')
  const input = join(SRC, file)
  const widths = []
  for (const w of WIDTHS) {
    const out = join(OUT_DIR, `${base}-${w}.webp`)
    try {
      encode(input, out, w)
      widths.push(w)
      made++
    } catch {
      // A variant that cannot be encoded is simply omitted; the base image
      // remains available as a fallback.
    }
  }
  variants.set(file, widths)
}

/** Builds a srcset plus the matching `sizes` value for a given slot. */
function entry(file) {
  const widths = variants.get(file) ?? []
  if (widths.length === 0) return null
  const srcset = widths.map((w) => `/images/property/resp/${file.replace(/\.webp$/, '')}-${w}.webp ${w}w`).join(', ')
  return { srcset, widths: widths.slice().sort((a, b) => a - b) }
}

const names = [...variants.keys()].sort()
const map = {}
for (const file of names) {
  const e = entry(file)
  if (e) map[file] = e
}

writeFileSync(
  join(ROOT, 'lib', 'property-image-sizes.generated.ts'),
  `// AUTO-GENERATED by scripts/generate-responsive-images.mjs — do not edit by hand.
import type { ImageVariant } from '@/lib/images'

export const imageVariants: Record<string, ImageVariant> = ${JSON.stringify(map, null, 0)}
`,
  'utf8',
)

console.log(`[responsive] ${made} variants across ${Object.keys(map).length} images (${WIDTHS.join('/')}w @ q${QUALITY})`)
