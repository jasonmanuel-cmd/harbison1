/**
 * Generates lib/property-images.generated.ts by scanning public/images/property.
 *
 * Why this exists: the gallery counts used to be hardcoded (Array.from({length:
 * 24})), but the listings do not all have 24 photos — several have between 6
 * and 22. That shipped broken image slots to visitors on those galleries. The
 * list has to come from what is actually on disk.
 *
 * It is generated rather than read at runtime because lib/site.ts is imported
 * by client components, and node:fs cannot be bundled for the browser. The
 * pages that need the galleries are statically generated, so scanning once at
 * build time is equivalent and costs nothing per request.
 *
 * Run automatically by `pnpm prebuild`; regenerate with:
 *   node scripts/generate-image-manifest.mjs
 */
import { readdirSync, writeFileSync, existsSync } from 'node:fs'
import { join } from 'node:path'

const ROOT = process.cwd()
const DIR = join(ROOT, 'public', 'images', 'property')
const OUT = join(ROOT, 'lib', 'property-images.generated.ts')

if (!existsSync(DIR)) {
  console.error(`[image-manifest] missing ${DIR}`)
  process.exit(1)
}

const files = readdirSync(DIR).filter((f) => f.endsWith('.webp'))

/** Groups "2300-weybridge-dr-3.webp" under prefix "2300-weybridge-dr". */
function collect(prefix) {
  const re = new RegExp(`^${prefix.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}-(\\d+)\\.webp$`)
  return files
    .map((f) => {
      const m = re.exec(f)
      return m ? { n: Number(m[1]), file: f } : null
    })
    .filter(Boolean)
    .sort((a, b) => a.n - b.n)
    .map((a) => `/images/property/${a.file}`)
}

const slugs = [
  '18211-sulky-ln',
  '21204-stage-dr',
  '2206-ribble-valley-dr',
  '22208-mariposa',
  '2300-weybridge-dr',
  '28211-seabiscuit-way',
  '28751-gleneagle-ct',
  '2901-summit-cir',
  '3109-mount-vernon-ave',
  '505-jeffrey-st',
  '909-oberlin-ct',
  '958-fairway-dr',
  'chalet-tehachapi',
]

const entries = slugs.map((slug) => `  ${JSON.stringify(slug)}: ${JSON.stringify(collect(slug))},`)

// 585 N Wendy Dr's photos are named wendy1..wendy18 rather than <slug>-<n>.
const wendy = files
  .map((f) => {
    const m = /^wendy(\d+)\.webp$/.exec(f)
    return m ? { n: Number(m[1]), file: f } : null
  })
  .filter(Boolean)
  .sort((a, b) => a.n - b.n)
  .map((a) => `/images/property/${a.file}`)

const body = `// AUTO-GENERATED by scripts/generate-image-manifest.mjs — do not edit by hand.
// Run \`node scripts/generate-image-manifest.mjs\` after adding or removing photos.

/** Real gallery image paths per listing, discovered from disk. */
export const propertyImages: Record<string, string[]> = {
${entries.join('\n')}
  '585-n-wendy-dr': ${JSON.stringify(wendy)},
}
`

writeFileSync(OUT, body, 'utf8')

const total = slugs.reduce((n, s) => n + collect(s).length, 0) + wendy.length
console.log(`[image-manifest] ${slugs.length} listings, ${total} images -> lib/property-images.generated.ts`)
